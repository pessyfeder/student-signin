// Builds the app as a static single-page app and packs it into ./offline with a tiny local
// server and a Windows launcher. Copy the whole ./offline folder to the school device.
import { execSync } from "node:child_process";
import { cpSync, rmSync, mkdirSync, renameSync, readdirSync, statSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, relative } from "node:path";

const out = "offline";
rmSync(out, { recursive: true, force: true });
execSync("npx vite build", {
  stdio: "inherit",
  env: { ...process.env, OFFLINE_BUILD: "1", VITE_OFFLINE_BUILD: "1" },
});

const app = join(out, "app");
mkdirSync(out, { recursive: true });
cpSync(".output/public", app, { recursive: true });
renameSync(join(app, "_shell.html"), join(app, "index.html"));
if (existsSync(join(app, "_headers"))) rmSync(join(app, "_headers"));

const files = [];
(function walk(dir) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else files.push("/" + relative(app, p).split("\\").join("/"));
  }
})(app);

const hash = createHash("sha256");
for (const f of files.sort()) hash.update(f).update(readFileSync(join(app, f)));
const version = hash.digest("hex").slice(0, 12);
const precache = ["/", ...files.filter((f) => f !== "/sw.js")];

writeFileSync(
  join(app, "sw.js"),
  `// Generated by scripts/build-offline.mjs. Caches the whole app so it works with no network.
const CACHE = "signin-${version}";
const FILES = ${JSON.stringify(precache)};
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener("fetch", (e) => {
  if (e.request.method !== "GET") return;
  const url = new URL(e.request.url);
  if (url.origin !== location.origin) return;
  const key = e.request.mode === "navigate" ? "/" : e.request;
  e.respondWith(
    caches.match(key).then((hit) => hit || fetch(e.request).catch(() => caches.match("/"))),
  );
});
`,
);

cpSync("scripts/offline-server.mjs", join(out, "server.mjs"));
writeFileSync(
  join(out, "Start Sign-In.bat"),
  `@echo off\r\ncd /d "%~dp0"\r\nnode server.mjs\r\nif errorlevel 1 (\r\n  echo.\r\n  echo Could not start. Is Node.js installed? Get it from https://nodejs.org\r\n  pause\r\n)\r\n`,
);
writeFileSync(
  join(out, "README.txt"),
  `Class Sign-In (offline)\r\n\r\n1. Install Node.js (LTS) once from https://nodejs.org. No internet is needed after that.\r\n2. Double-click "Start Sign-In.bat". The app opens at http://localhost:4173\r\n3. Always use that same address and the same browser: the records live in that browser.\r\n4. In Chrome or Edge, use the install icon in the address bar (or menu > Install) to add it\r\n   as an app. After the first visit it also works with the server stopped.\r\n5. Use the Backup tab in Admin regularly.\r\n`,
);
console.log(`\nOffline build ready in ./${out} (cache ${version})`);
