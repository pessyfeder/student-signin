// Builds the app as a static single-page app and packs it into ./offline with a tiny local
// server and a Windows launcher. Copy the whole ./offline folder to the school device.
import { execSync } from "node:child_process";
import { cpSync, rmSync, mkdirSync, renameSync, readdirSync, statSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, relative } from "node:path";

const out = "offline";
// Empty the folder rather than deleting it: Windows refuses to delete a folder that a running
// launcher window is sitting in.
mkdirSync(out, { recursive: true });
try {
  for (const f of readdirSync(out)) rmSync(join(out, f), { recursive: true, force: true });
} catch (e) {
  console.error(
    `\nCould not clear ./offline (${e.code}). Close the Sign-In server window if it is running, then try again.`,
  );
  process.exit(1);
}
execSync("npx vite build", {
  stdio: "inherit",
  env: { ...process.env, OFFLINE_BUILD: "1", VITE_OFFLINE_BUILD: "1" },
});

const app = join(out, "app");
mkdirSync(out, { recursive: true });
cpSync(".output/public", app, { recursive: true });
renameSync(join(app, "_shell.html"), join(app, "index.html"));
if (existsSync(join(app, "_headers"))) rmSync(join(app, "_headers"));

const files = [];
(function walk(dir) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else files.push("/" + relative(app, p).split("\\").join("/"));
  }
})(app);

const hash = createHash("sha256");
for (const f of files.sort()) hash.update(f).update(readFileSync(join(app, f)));
const version = hash.digest("hex").slice(0, 12);
const precache = ["/", ...files.filter((f) => f !== "/sw.js")];

writeFileSync(
  join(app, "sw.js"),
  `// Generated by scripts/build-offline.mjs. Caches the whole app so it works with no network.
const CACHE = "signin-${version}";
const FILES = ${JSON.stringify(precache)};
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener("fetch", (e) => {
  if (e.request.method !== "GET") return;
  const url = new URL(e.request.url);
  if (url.origin !== location.origin) return;
  const key = e.request.mode === "navigate" ? "/" : e.request;
  e.respondWith(
    caches.match(key).then((hit) => hit || fetch(e.request).catch(() => caches.match("/"))),
  );
});
`,
);

cpSync("scripts/offline-server.ps1", join(out, "server.ps1"));
// Windows batch files and text files want CRLF line endings.
const crlf = (lines) => lines.join("\r\n") + "\r\n";
writeFileSync(
  join(out, "Start Sign-In.bat"),
  crlf([
    "@echo off",
    'cd /d "%~dp0"',
    'powershell -NoProfile -ExecutionPolicy Bypass -File "%~dp0server.ps1"',
    "if errorlevel 1 pause",
  ]),
);
writeFileSync(
  join(out, "README.txt"),
  crlf([
    "Class Sign-In (offline)",
    "",
    "Nothing needs to be installed. Windows 10 or 11 is enough.",
    "",
    '1. Double-click "Start Sign-In.bat". A window opens and the app opens in your browser',
    "   at http://localhost:4173",
    "2. Leave that window open (minimize it). Closing it stops the app.",
    "3. Always use that same address and the same browser: the records live in that browser.",
    "4. In Chrome or Edge, use the install icon in the address bar (or menu > Install) to add",
    "   it as an app.",
    "5. Use the Backup tab in Admin regularly.",
  ]),
);
console.log(`\nOffline build ready in ./${out} (cache ${version})`);
